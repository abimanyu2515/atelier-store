import { relations, sql } from "drizzle-orm";
import {
  boolean,
  check,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  text,
  timestamp,
  unique,
  uuid,
} from "drizzle-orm/pg-core";
import { user } from "./auth";
import { products, sizeSystem } from "./catalog";
import { timestamps } from "./columns";

/**
 * Where an order is in payment. Stock is reserved while `pending` or
 * `processing`, and returned when an order moves to `failed` or `expired`.
 * `processing` is a delayed payment method (e.g. bank debit) still clearing.
 * `refunded` keeps its stock out; an admin decides whether to restock.
 */
export const orderStatus = pgEnum("order_status", [
  "pending",
  "processing",
  "paid",
  "failed",
  "expired",
  "refunded",
]);

/** A shipping address as Stripe Checkout collects it. */
export type ShippingAddress = {
  line1: string | null;
  line2: string | null;
  city: string | null;
  state: string | null;
  postalCode: string | null;
  country: string | null;
};

/**
 * One checkout attempt by a signed-in customer. Totals are computed from
 * products.price_cents when the order is created, never from the browser.
 * Amounts from Stripe are stored separately so a mismatch can be flagged.
 */
export const orders = pgTable(
  "orders",
  {
    // Generated by the app too, so one batch can insert an order and its items.
    id: uuid("id").primaryKey().defaultRandom(),
    // Restrict: deleting a customer must not delete their order history.
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "restrict" }),
    status: orderStatus("status").notNull().default("pending"),
    /** Lowercase ISO 4217, as Stripe reports it. */
    currency: text("currency").notNull().default("usd"),
    subtotalCents: integer("subtotal_cents").notNull(),
    totalCents: integer("total_cents").notNull(),
    /** Stripe's amount_total, set when the order is paid. */
    amountPaidCents: integer("amount_paid_cents"),
    /** Null until the Checkout Session is created. */
    stripeCheckoutSessionId: text("stripe_checkout_session_id").unique(),
    stripePaymentIntentId: text("stripe_payment_intent_id").unique(),
    /** Contact and shipping details from the completed Checkout Session. */
    email: text("email"),
    shippingName: text("shipping_name"),
    shippingAddress: jsonb("shipping_address").$type<ShippingAddress>(),
    /** When the Checkout Session, and so the stock reservation, expires. */
    reservationExpiresAt: timestamp("reservation_expires_at", { withTimezone: true }),
    paidAt: timestamp("paid_at", { withTimezone: true }),
    /** Stripe's amount or currency differed from ours; check before shipping. */
    needsReview: boolean("needs_review").notNull().default(false),
    ...timestamps,
  },
  (table) => [
    index("orders_user_id_created_at_idx").on(table.userId, table.createdAt.desc()),
    // For the sweeper that releases reservations whose webhook never arrived.
    index("orders_pending_expires_at_idx")
      .on(table.reservationExpiresAt)
      .where(sql`${table.status} = 'pending'`),
    check("orders_currency_check", sql`${table.currency} ~ '^[a-z]{3}$'`),
    check(
      "orders_amounts_check",
      sql`${table.subtotalCents} >= 0 and ${table.totalCents} >= 0 and ${table.amountPaidCents} >= 0`,
    ),
    // Anything past pending went through Stripe, and paid orders record the payment.
    check(
      "orders_stripe_session_check",
      sql`${table.status} not in ('processing', 'paid', 'refunded') or ${table.stripeCheckoutSessionId} is not null`,
    ),
    check(
      "orders_paid_fields_check",
      sql`${table.status} not in ('paid', 'refunded') or (${table.paidAt} is not null and ${table.amountPaidCents} is not null and ${table.stripePaymentIntentId} is not null)`,
    ),
  ],
);

/**
 * What was bought, frozen at checkout. Name, price and size are copied so the
 * order still reads correctly after the product changes or is deleted.
 */
export const orderItems = pgTable(
  "order_items",
  {
    id: integer("id").primaryKey().generatedAlwaysAsIdentity(),
    orderId: uuid("order_id")
      .notNull()
      .references(() => orders.id, { onDelete: "cascade" }),
    /** Null once the product is deleted; the snapshot below remains. */
    productId: integer("product_id").references(() => products.id, { onDelete: "set null" }),
    productSlug: text("product_slug").notNull(),
    productName: text("product_name").notNull(),
    color: text("color").notNull(),
    /** "" for products without sizes, matching cart_items. */
    size: text("size").notNull().default(""),
    sizeSystem: sizeSystem("size_system"),
    imageUrl: text("image_url"),
    unitPriceCents: integer("unit_price_cents").notNull(),
    quantity: integer("quantity").notNull(),
  },
  (table) => [
    // Leads with order_id, so it also serves "this order's items" lookups.
    unique("order_items_order_product_size_key").on(
      table.orderId,
      table.productSlug,
      table.size,
    ),
    // Lets product deletes find rows to null out without a full scan.
    index("order_items_product_id_idx").on(table.productId),
    check("order_items_quantity_check", sql`${table.quantity} > 0`),
    check("order_items_unit_price_cents_check", sql`${table.unitPriceCents} >= 0`),
  ],
);

/**
 * Stripe webhook events already handled, keyed by Stripe's event id. A
 * shortcut for redeliveries; order updates are idempotent on their own.
 */
export const stripeEvents = pgTable("stripe_events", {
  id: text("id").primaryKey(),
  type: text("type").notNull(),
  processedAt: timestamp("processed_at", { withTimezone: true }).notNull().defaultNow(),
});

export const ordersRelations = relations(orders, ({ one, many }) => ({
  user: one(user, {
    fields: [orders.userId],
    references: [user.id],
  }),
  items: many(orderItems),
}));

export const orderItemsRelations = relations(orderItems, ({ one }) => ({
  order: one(orders, {
    fields: [orderItems.orderId],
    references: [orders.id],
  }),
  product: one(products, {
    fields: [orderItems.productId],
    references: [products.id],
  }),
}));
